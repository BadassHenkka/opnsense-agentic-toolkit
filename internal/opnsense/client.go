// Package opnsense is a small client for the OPNsense REST API. It is shared by the
// MCP server and the Terraform provider.
package opnsense

import (
	"bytes"
	"context"
	"crypto/tls"
	"crypto/x509"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"os"
	"strings"
	"sync"
	"time"
)

// Environment variables read by ConfigFromEnv.
const (
	EnvURL       = "OPNSENSE_URL"
	EnvAPIKey    = "OPNSENSE_API_KEY"
	EnvAPISecret = "OPNSENSE_API_SECRET"
	EnvCAFile    = "OPNSENSE_CA_FILE"
	EnvInsecure  = "OPNSENSE_INSECURE"
	// EnvTLSServerName overrides the name the certificate is checked against.
	EnvTLSServerName = "OPNSENSE_TLS_SERVER_NAME"
)

// Config holds what is needed to talk to one OPNsense instance.
type Config struct {
	// URL is the base URL of the web UI, e.g. https://opnsense.lan. The /api prefix is added.
	URL       string
	APIKey    string
	APISecret string
	// CAFile is an optional PEM bundle used to verify a self-signed certificate.
	CAFile string
	// Insecure disables TLS verification. Prefer CAFile.
	Insecure bool
	// TLSServerName, if set, is the name the certificate must be valid for, and the name sent
	// in SNI. The connection still goes to the host in URL. Use it to reach a firewall by an
	// address its certificate does not list, such as a test copy that has the real one's
	// certificate.
	TLSServerName string
	// Timeout per request. Zero means 30 seconds.
	Timeout time.Duration
	// HTTPClient overrides the client built from the fields above (used in tests).
	HTTPClient *http.Client
}

// ConfigFromEnv reads a Config from OPNSENSE_* environment variables.
func ConfigFromEnv() Config {
	return Config{
		URL:       os.Getenv(EnvURL),
		APIKey:    os.Getenv(EnvAPIKey),
		APISecret: os.Getenv(EnvAPISecret),
		CAFile:    os.Getenv(EnvCAFile),
		Insecure:  os.Getenv(EnvInsecure) == "1" || strings.EqualFold(os.Getenv(EnvInsecure), "true"),

		TLSServerName: os.Getenv(EnvTLSServerName),
	}
}

// Client talks to the OPNsense API.
type Client struct {
	// generatedServices holds the areas generated by cmd/opnsense-gen (zz_gen_*.go).
	generatedServices

	base      *url.URL
	key       string
	secret    string
	http      *http.Client
	userAgent string

	// applyMu serialises reconfigure calls; OPNsense handles parallel service reloads poorly
	// and Terraform runs resources in parallel.
	applyMu sync.Mutex

	// Filter manages firewall filter rules.
	Filter *FilterService
	// Firmware manages packages, plugins and firmware updates.
	Firmware *FirmwareService
	// Backup reads configuration backups and ZFS snapshots.
	Backup *BackupService
}

// NewClient validates cfg and returns a Client.
func NewClient(cfg Config) (*Client, error) {
	if cfg.URL == "" {
		return nil, errors.New("opnsense: URL is required")
	}
	if cfg.APIKey == "" || cfg.APISecret == "" {
		return nil, errors.New("opnsense: API key and secret are required")
	}
	base, err := url.Parse(strings.TrimRight(cfg.URL, "/"))
	if err != nil {
		return nil, fmt.Errorf("opnsense: invalid URL: %w", err)
	}
	if base.Scheme != "https" && base.Scheme != "http" {
		return nil, fmt.Errorf("opnsense: URL must start with https:// (got %q)", cfg.URL)
	}

	hc := cfg.HTTPClient
	if hc == nil {
		hc, err = newHTTPClient(cfg)
		if err != nil {
			return nil, err
		}
	}

	c := &Client{
		base:      base,
		key:       cfg.APIKey,
		secret:    cfg.APISecret,
		http:      hc,
		userAgent: "opnsense-agentic-toolkit",
	}
	c.Filter = newFilterService(c)
	c.Firmware = newFirmwareService(c)
	c.Backup = newBackupService(c)
	c.initGenerated()
	return c, nil
}

func newHTTPClient(cfg Config) (*http.Client, error) {
	tlsCfg := &tls.Config{MinVersion: tls.VersionTLS12, ServerName: cfg.TLSServerName}
	if cfg.CAFile != "" {
		pem, err := os.ReadFile(cfg.CAFile)
		if err != nil {
			return nil, fmt.Errorf("opnsense: read CA file: %w", err)
		}
		pool := x509.NewCertPool()
		if !pool.AppendCertsFromPEM(pem) {
			return nil, fmt.Errorf("opnsense: no certificates found in %s", cfg.CAFile)
		}
		tlsCfg.RootCAs = pool
	}
	if cfg.Insecure {
		tlsCfg.InsecureSkipVerify = true //nolint:gosec // explicit opt-in
	}
	timeout := cfg.Timeout
	if timeout == 0 {
		timeout = 30 * time.Second
	}
	tr := http.DefaultTransport.(*http.Transport).Clone()
	tr.TLSClientConfig = tlsCfg
	return &http.Client{Transport: tr, Timeout: timeout}, nil
}

// SetUserAgent sets the User-Agent sent with every request.
func (c *Client) SetUserAgent(ua string) { c.userAgent = ua }

// Get calls GET /api/<path> and decodes the JSON response into out.
func (c *Client) Get(ctx context.Context, path string, out any) error {
	return c.do(ctx, http.MethodGet, path, nil, out)
}

// Post calls POST /api/<path> with body encoded as JSON and decodes the response into out.
// A nil body sends an empty JSON object, which OPNsense expects for action endpoints.
func (c *Client) Post(ctx context.Context, path string, body, out any) error {
	if body == nil {
		body = struct{}{}
	}
	return c.do(ctx, http.MethodPost, path, body, out)
}

func (c *Client) do(ctx context.Context, method, path string, body, out any) error {
	u := c.base.JoinPath("api", path)

	var rdr io.Reader
	if body != nil {
		buf, err := json.Marshal(body)
		if err != nil {
			return fmt.Errorf("opnsense: encode request: %w", err)
		}
		rdr = bytes.NewReader(buf)
	}

	req, err := http.NewRequestWithContext(ctx, method, u.String(), rdr)
	if err != nil {
		return err
	}
	req.SetBasicAuth(c.key, c.secret)
	req.Header.Set("Accept", "application/json")
	req.Header.Set("User-Agent", c.userAgent)
	if body != nil {
		// OPNsense rejects GETs that carry a Content-Type, so only set it with a body.
		req.Header.Set("Content-Type", "application/json")
	}

	resp, err := c.http.Do(req)
	if err != nil {
		return fmt.Errorf("opnsense: %s %s: %w", method, path, err)
	}
	defer func() { _ = resp.Body.Close() }()

	data, err := io.ReadAll(io.LimitReader(resp.Body, 32<<20))
	if err != nil {
		return fmt.Errorf("opnsense: read response: %w", err)
	}
	if resp.StatusCode < 200 || resp.StatusCode > 299 {
		return &APIError{Method: method, Path: path, StatusCode: resp.StatusCode, Body: truncate(string(data), 512)}
	}
	if out == nil || len(data) == 0 {
		return nil
	}
	if err := json.Unmarshal(data, out); err != nil {
		return fmt.Errorf("opnsense: decode %s response: %w", path, err)
	}
	return nil
}

// Reconfigure calls a service's reconfigure (apply) action, one at a time per client.
// Services answer {"status":"ok"} or, like WireGuard, {"result":"ok"}.
func (c *Client) Reconfigure(ctx context.Context, path string) error {
	c.applyMu.Lock()
	defer c.applyMu.Unlock()
	var resp struct {
		Status string `json:"status"`
		Result string `json:"result"`
	}
	if err := c.Post(ctx, path, nil, &resp); err != nil {
		return err
	}
	for _, v := range []string{resp.Status, resp.Result} {
		if s := strings.ToLower(strings.TrimSpace(v)); s != "ok" && s != "" {
			return fmt.Errorf("opnsense: %s returned %q", path, v)
		}
	}
	return nil
}

func truncate(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return s[:n] + "…"
}

// VerifyReachable checks over a new TCP connection that the API still answers, retrying for up
// to wait (default 10s). Changes to firewall rules, NAT or interfaces can cut off the client
// that made them; existing connections may survive in the state table while new ones fail.
func (c *Client) VerifyReachable(ctx context.Context, wait time.Duration) error {
	if wait <= 0 {
		wait = 10 * time.Second
	}
	deadline := time.Now().Add(wait)
	for {
		c.http.CloseIdleConnections() // force a new connection through the new configuration
		probe, cancel := context.WithTimeout(ctx, 3*time.Second)
		var resp map[string]any
		last := c.Get(probe, "core/firmware/running", &resp)
		cancel()
		if last == nil {
			return nil
		}
		if time.Now().After(deadline) || ctx.Err() != nil {
			return fmt.Errorf("the API is no longer reachable over a new connection (%v)", last)
		}
		time.Sleep(500 * time.Millisecond)
	}
}
